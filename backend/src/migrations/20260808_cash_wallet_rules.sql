-- Objetivo:
-- 1) Registrar metodo de pago en reservas/viajes/historial.
-- 2) Llevar wallet virtual del chofer con limite de deuda en efectivo.
-- 3) Exponer funciones SQL para validar si un chofer puede aceptar viajes.

-- Metodo de pago en reservas
alter table if exists public.reservas
  add column if not exists metodo_pago text;

alter table if exists public.reservas
  add column if not exists payment_method text;

alter table if exists public.reservas
  add column if not exists comision_plataforma numeric(12,2);

update public.reservas
set metodo_pago = coalesce(nullif(trim(metodo_pago), ''), nullif(trim(payment_method), ''), 'tarjeta')
where metodo_pago is null or trim(metodo_pago) = '';

update public.reservas
set payment_method = coalesce(nullif(trim(payment_method), ''), nullif(trim(metodo_pago), ''), 'tarjeta')
where payment_method is null or trim(payment_method) = '';

alter table if exists public.reservas
  alter column metodo_pago set default 'tarjeta';

alter table if exists public.reservas
  alter column payment_method set default 'tarjeta';

